const ALLOWED = new Set([...ACCELERATORS, ...FULL_NAMES])
// Attribute classes may be written without their suffix and are listed above in both spellings.

/**
 * The name the list is compared by: lower-case, array brackets removed (an array of an allowed type is allowed) and generic
 * arguments removed (the outer type decides).
 */
export function normalize(name: string) {
  let result = name.trim().toLowerCase()
  while (result.endsWith("[]")) result = result.slice(0, -2)
  const generic = result.indexOf("[")
  if (generic > 0 && result.endsWith("]")) result = result.slice(0, generic)
  return result
}

/** Whether Constrained Language Mode allows the type, written as in the source (`[int]`, `System.String[]`). */
export function allowed(name: string) {
  return ALLOWED.has(normalize(name))
}
